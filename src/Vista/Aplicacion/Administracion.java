    public void crearCabecera() {
        tablaMisUsuarios.addColumn("Usuario");
        tablaMisUsuarios.addColumn("Nombre");
        tablaMisUsuarios.addColumn("Contrasena");
        tablaMisUsuarios.addColumn("Cargo");
        tablaMisUsuarios.addColumn("Permisos");
        tablaMisUsuarios.addColumn("Respuestas de Seguridad");
        tablaUsers.setModel(tablaMisUsuarios);
    }

    public void llenarTablaUsers() {
        tablaMisUsuarios.setRowCount(0);

        // Iterar sobre el arreglo cables y agregar los datos a la tabla
        ArrayList<Usuarios> myUs = new ArrayList<>();
        UsuariosDAO go = new UsuariosDAO();
        myUs = go.listarTodos();
        for (int i = 0; i < myUs.size(); i++) {
            String mispermix = "";
            String mispreguntix = "";
            for (int j = 0; j < myUs.get(i).getLosPermisos().size(); j++) {
                mispermix = mispermix + myUs.get(i).getLosPermisos().get(j).getNombre_permiso() + ", ";
            }
            for (int k = 0; k < myUs.get(i).getLasPreguntas().size(); k++) {
                mispreguntix = mispreguntix + myUs.get(i).getLasPreguntas().get(k).getRespuesta() + ", ";

            }
            Object[] datos = {
                myUs.get(i).getUsuario(),
                myUs.get(i).getNombre(),
                myUs.get(i).getPassword(),
                myUs.get(i).getLosCargos().getNombre_Cargo(),
                mispermix,
                mispreguntix
            };
            tablaMisUsuarios.addRow(datos);
        }

    }


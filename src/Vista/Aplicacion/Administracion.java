    private void tablaUsersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaUsersMouseClicked
        int fila = tablaUsers.getSelectedRow();
        if (fila != -1) {
            DefaultTableModel modelo = (DefaultTableModel) tablaUsers.getModel();

            String usuario = modelo.getValueAt(fila, 0).toString();
            UsuariosDAO ok = new UsuariosDAO();
            Usuarios usuarioC = ok.listarUno(usuario);
            
            usuarioSelec = usuarioC; 

            nombre.setText(usuarioC.getNombre());
            user.setText(usuarioC.getUsuario());
            pass.setText(usuarioC.getPassword());
            cargo.setSelectedIndex(usuarioC.getLosCargos().getId_cargo());

            ArrayList<Permisos> permisos = usuarioC.getLosPermisos();

            //desmarcar todos por defecto:
            restablecerPermisos();

            //marcar según los permisos del usuario
            for (Permisos p : permisos) {
                switch (p.getId_permiso()) {
                    case 2:
                        venta.setSelected(true);
                        break;
                    case 1:
                        reporte.setSelected(true);
                        break;
                    case 4:
                        cliente.setSelected(true);
                        break;
                    case 3:
                        almacen.setSelected(true);
                        break;
                    case 5:
                        administrar.setSelected(true);
                        break;
                }
            }

        }
    }//GEN-LAST:event_tablaUsersMouseClicked


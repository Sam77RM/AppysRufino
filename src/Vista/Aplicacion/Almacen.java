        private void llenarTablaCables() {
        // Iterar sobre el arreglo cables y agregar los datos a la tabla
            CablesDAO conex = new CablesDAO();
            ArrayList<Cable>  listaCables = new ArrayList<>();
            listaCables = conex.listarTodos();
        for (int i = 0; i < listaCables.size(); i++) {
            
            Object[] fila = {
                listaCables.get(i).getCodigo(),
                listaCables.get(i).getTipo(), 
                listaCables.get(i).getMarca_auto(), 
                listaCables.get(i).getModelo_auto(),
                listaCables.get(i).getAnio_auto(),
                listaCables.get(i).getCantidad(), 
                listaCables.get(i).getMarcaC(),
                listaCables.get(i).getPrecioUnt(),
                listaCables.get(i).getPrecioCosto()
            };
            tablaCables.addRow(fila); // Agregar la fila al modelo

        }
    }
    
        
        private void llenarTablaRepuestos() {
        // Iterar sobre el arreglo cables y agregar los datos a la tabla
        for (int i = 0; i < GestRepuestos.getRepuestoCont(); i++) {
            Repuesto mirepuesto = GestRepuestos.getRepuestos()[i]; // Obtener el cable actual
            Object[] fila = {
                mirepuesto.getCodigo(), 
                mirepuesto.getTipo(), 
                mirepuesto.getMarca(), 
                mirepuesto.getCantidad(), 
                mirepuesto.getTamano()
            };

            tablaRepuestos.addRow(fila); // Agregar la fila al modelo

        }
    }
            

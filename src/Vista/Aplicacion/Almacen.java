    private void BuscarBotonMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_BuscarBotonMouseClicked
        vaciarTabla();
        llenarTablaCables(); 
        
        
        for (int i = tablaCables.getRowCount() - 1; i >= 0; i--) { // Recorrer de atrás hacia adelante

                 if (!marcaAuto.getText().equals("")&&!marcaAuto.getText().equalsIgnoreCase((String) tablaCables.getValueAt(i, 2))) { //! negacion
                    tablaCables.removeRow(i); // Eliminar fila que no coincide
                } else if (!modeloAuto.getText().equals("")&&!modeloAuto.getText().equalsIgnoreCase(String.valueOf(tablaCables.getValueAt(i, 3)))) { //! negacion
                    tablaCables.removeRow(i); // Eliminar fila que no coincide
                } else if (!tipoCable.getText().equals("")&&!tipoCable.getText().equalsIgnoreCase((String) tablaCables.getValueAt(i, 1))) { //! negacion
                    tablaCables.removeRow(i); // Eliminar fila que no coincide
                } else if (!marcaCable.getText().equals("")&&!marcaCable.getText().equalsIgnoreCase((String) tablaCables.getValueAt(i, 6))) { //! negacion
                    tablaCables.removeRow(i); // Eliminar fila que no coincide
                } else if (!anioAuto.getText().equals("")&&!anioAuto.getText().equalsIgnoreCase(String.valueOf(tablaCables.getValueAt(i, 4)))) { //! negacion
                    tablaCables.removeRow(i); // Eliminar fila que no coincide
                } else if (!codigo.getText().equals("")&&!codigo.getText().equalsIgnoreCase((String) tablaCables.getValueAt(i, 0))) { //! negacion
                    tablaCables.removeRow(i); // Eliminar fila que no coincide
                }                     
    }
    }//GEN-LAST:event_BuscarBotonMouseClicked

